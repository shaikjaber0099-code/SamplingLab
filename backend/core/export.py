"""
Export module for The Sampling Lab.
Generates comprehensive Markdown reports, CSV datasets, and JSON archives of experimental runs.
"""

import io
import csv
import json
from datetime import datetime
from typing import Dict, Any, List


def fmt_val(val, decimals=3, suffix=""):
    """Format numerical metric or return 'N/A' if None or invalid."""
    if val is None or val == "":
        return "N/A"
    try:
        return f"{float(val):.{decimals}f}{suffix}"
    except (ValueError, TypeError):
        return str(val)


def export_markdown_report(data: Dict[str, Any]) -> str:
    """
    Generate a formatted lab experiment Markdown report.
    Includes:
    - Experiment metadata & parameters
    - Temperature sweep comparison table (FR-09)
    - Generated samples grouped by heat level
    - Scientific observations & Lab Notes (FR-16, FR-17)
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    prompt = data.get("prompt", "")
    provider = data.get("provider", "Local GPT-2")
    model_name = data.get("model", "distilgpt2")
    top_p = data.get("top_p", 1.0)
    top_k = data.get("top_k", 0)
    seed = data.get("seed", "Random")
    rep_penalty = data.get("repetition_penalty", 1.15)
    ngram_size = data.get("no_repeat_ngram_size", 3)
    runs = data.get("runs", [])
    observations = data.get("observations", {})
    user_notes = data.get("user_notes", "")
    conclusion = data.get("conclusion", "")

    md = []
    md.append("# 🔬 The Sampling Lab — Text Generation Parameter Report")
    md.append(f"**Generated:** {timestamp}  ")
    md.append(f"**Model / Engine:** `{model_name}` ({provider})  ")
    md.append(f"**Seed:** `{seed}` | **Top-p:** `{top_p}` | **Top-k:** `{top_k}` | **Repetition Penalty:** `{rep_penalty}` | **No-Repeat N-gram:** `{ngram_size}`  \n")
    
    md.append("## 1. Input Prompt")
    md.append("```text")
    md.append(prompt)
    md.append("```\n")

    md.append("## 2. Quantitative Metrics Comparison")
    md.append("| Temperature | Heat State | Distinct-1 | Distinct-2 | Self-Similarity | Repetition Rate | Avg Tokens | Perplexity | Unique / N |")
    md.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    
    def get_heat_label(t):
        if t <= 0.05: return "❄️ Frozen (Argmax)"
        if t < 0.5: return "🧊 Focused"
        if t <= 0.9: return "⚖️ Balanced"
        if t <= 1.4: return "🔥 Creative"
        return "🌋 Chaotic"

    for r in runs:
        t = r.get("temperature", 0.0)
        m = r.get("metrics", {})
        d1 = fmt_val(m.get("distinct_1"))
        d2 = fmt_val(m.get("distinct_2"))
        sim = fmt_val(m.get("self_similarity"))
        rep = fmt_val((m.get("repetition_rate") * 100) if m.get("repetition_rate") is not None else None, decimals=1, suffix="%")
        avg_tokens = fmt_val(m.get("avg_tokens", m.get("avg_words")), decimals=1)
        ppl = fmt_val(m.get("perplexity"), decimals=2)
        u_count = f"{m.get('unique_samples', 1)}/{m.get('total_samples', 1)}"
        md.append(f"| **T = {t:.1f}** | {get_heat_label(t)} | {d1} | {d2} | {sim} | {rep} | {avg_tokens} | {ppl} | {u_count} |")
    
    md.append("\n## 3. Generated Samples per Temperature\n")
    for r in runs:
        t = r.get("temperature", 0.0)
        samples = r.get("samples", [])
        m = r.get("metrics", {})
        is_det = m.get("is_deterministic", False)
        
        det_badge = " *(100% Identical Outputs / Argmax Locked)*" if is_det else ""
        md.append(f"### Temperature = {t:.1f} — {get_heat_label(t)}{det_badge}")
        
        for idx, s in enumerate(samples, 1):
            text = s if isinstance(s, str) else s.get("text", "")
            tokens_count = s.get("tokens_count") if isinstance(s, dict) else len(text.split())
            ppl_str = f" | Perplexity: {s.get('perplexity'):.2f}" if (isinstance(s, dict) and s.get("perplexity")) else ""
            
            md.append(f"**Sample #{idx}** (`Tokens: {tokens_count}`{ppl_str}):")
            md.append("```text")
            md.append(text.strip())
            md.append("```\n")

    md.append("## 4. Empirical Observations")
    bullet_points = observations.get("bullet_points", []) if isinstance(observations, dict) else []
    if bullet_points:
        for b in bullet_points:
            md.append(f"- {b}")
    else:
        md.append("- No automated observations recorded.")
    md.append("")

    if user_notes:
        md.append("## 5. Experimenter Lab Notes")
        md.append(f"> {user_notes}\n")

    if conclusion:
        md.append("## 6. Scientific Conclusion")
        md.append(f"{conclusion}\n")

    md.append("---")
    md.append("*Report generated by The Sampling Lab — Probabilistic Text Generation Parameter Explorer.*")

    return "\n".join(md)


def export_csv_dataset(data: Dict[str, Any]) -> str:
    """Generate CSV string containing all samples, parameters, and per-temperature metrics."""
    output = io.StringIO()
    writer = csv.writer(output)
    
    # Header
    writer.writerow([
        "run_id",
        "temperature",
        "heat_label",
        "sample_index",
        "prompt",
        "generated_text",
        "token_count",
        "perplexity",
        "repetition_penalty",
        "no_repeat_ngram_size",
        "distinct_1",
        "distinct_2",
        "self_similarity",
        "repetition_rate",
        "unique_samples",
        "total_samples"
    ])
    
    runs = data.get("runs", [])
    prompt = data.get("prompt", "")
    rep_penalty = data.get("repetition_penalty", 1.15)
    ngram_size = data.get("no_repeat_ngram_size", 3)
    
    for r in runs:
        t = r.get("temperature", 0.0)
        m = r.get("metrics", {})
        samples = r.get("samples", [])
        
        for idx, s in enumerate(samples, 1):
            text = s if isinstance(s, str) else s.get("text", "")
            t_count = s.get("tokens_count", len(text.split())) if isinstance(s, dict) else len(text.split())
            ppl = s.get("perplexity", "N/A") if isinstance(s, dict) and s.get("perplexity") is not None else "N/A"
            
            writer.writerow([
                f"T_{t}",
                t,
                "Frozen" if t <= 0.05 else ("Focused" if t < 0.5 else ("Balanced" if t <= 0.9 else ("Creative" if t <= 1.4 else "Chaotic"))),
                idx,
                prompt,
                text.strip().replace("\n", " "),
                t_count,
                ppl,
                rep_penalty,
                ngram_size,
                fmt_val(m.get("distinct_1")),
                fmt_val(m.get("distinct_2")),
                fmt_val(m.get("self_similarity")),
                fmt_val(m.get("repetition_rate")),
                m.get("unique_samples", "1"),
                m.get("total_samples", "1")
            ])
            
    return output.getvalue()


def export_json_archive(data: Dict[str, Any]) -> str:
    """Export complete structured run archive as pretty JSON."""
    return json.dumps(data, indent=2)
